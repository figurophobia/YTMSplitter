"""Export and import label batches for external assistants (no API key)."""

from __future__ import annotations

import json
from collections.abc import Iterable, Iterator
from pathlib import Path

from . import config as C
from .ai import SYSTEM, TAXONOMY


def missing_songs(liked: list[dict], labels: dict[str, str]) -> list[dict]:
    """Return the songs that do not have a label yet."""
    return [track for track in liked if track["videoId"] not in labels]


def chunked(items: list[dict], size: int) -> list[list[dict]]:
    """Split a list into chunks of at most ``size`` items."""
    return [items[index : index + size] for index in range(0, len(items), size)]


def song_line(track: dict) -> str:
    artists = "; ".join(track.get("artists") or []) or "?"
    return (
        f"{track['videoId']} :: {track['title']} — {artists} || album: {track.get('album') or '-'}"
    )


def render_batch(songs: list[dict], index: int, total: int, batch_size: int) -> str:
    lines = "\n".join(song_line(track) for track in songs)
    return f"""# YTMSplitter label batch {index:03d}/{total:03d}

This file is a self-contained classification prompt. Read the rules and reply
with ONLY a JSON object that maps every videoId below to one label.

## System

{SYSTEM}

## Taxonomy

{TAXONOMY}

## Songs ({len(songs)})

```text
{lines}
```

## Output

Write the JSON object to `batch_{index:03d}.json` next to this file. It must map
every videoId to one of the labels above. Do not wrap it in markdown and do not
add explanations.

Example shape:

```json
{{"videoId": "label"}}
```

The batch size is {batch_size}; only the song lines above belong to this batch.
"""


def _readme(batch_count: int, batch_size: int, out_dir: Path) -> str:
    return f"""# Label batches

Generated by `ytmsplitter labels --export`.

There are **{batch_count}** batch file(s), each with up to {batch_size} songs.
Every `batch_NNN.md` is self-contained: it includes the system prompt, the
closed taxonomy and the song list. Ask an assistant to read it and write
`batch_NNN.json` with only the JSON object.

## opencode

```bash
opencode run "Read data/label_batches/batch_001.md and write the JSON object it asks for to data/label_batches/batch_001.json. Reply only with a short confirmation."
```

To process every batch in one session:

```bash
opencode run "Process every data/label_batches/batch_*.md file: write the matching .json file with only the JSON object. Do not edit anything else."
```

If opencode asks for permission to write files, run it interactively or add
`--auto` to the command. Add `--model provider/model` to choose a specific model.

## Claude Code

```bash
claude -p "Read data/label_batches/batch_001.md and write the JSON object to data/label_batches/batch_001.json. Reply only with a short confirmation." --allowedTools "Read,Write"
```

To process every batch in one session:

```bash
claude -p "Process every data/label_batches/batch_*.md file: write the matching .json file with only the JSON object. Do not edit anything else." --allowedTools "Read,Write,Glob"
```

If Claude Code asks for workspace trust, accept it or run `claude` interactively.

You can also open this directory in the interactive assistant and paste the same
instruction. Once the `.json` files exist, import them:

```bash
ytmsplitter labels --import
ytmsplitter ai --create
```

Files are read from `{out_dir}` by default. Use `--dir` to point at another
folder.
"""


def export_batches(
    liked: list[dict],
    labels: dict[str, str],
    out_dir: Path = C.LABEL_BATCH_DIR,
    batch_size: int = C.AI_BATCH_SIZE,
) -> tuple[list[Path], int]:
    """Write one prompt per missing-label batch. Return paths and missing count."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    batch_size = max(1, batch_size)

    # Remove stale prompts so the directory matches the current library.
    for old in out_dir.glob("batch_*.md"):
        old.unlink()

    missing = missing_songs(liked, labels)
    if not missing:
        (out_dir / "README.md").write_text(
            "# Label batches\n\nEvery song already has a label. Run `ytmsplitter ai --create`.\n",
            encoding="utf-8",
        )
        return [], 0

    batches = chunked(missing, batch_size)
    paths: list[Path] = []
    for index, batch in enumerate(batches, 1):
        path = out_dir / f"batch_{index:03d}.md"
        path.write_text(
            render_batch(batch, index, len(batches), batch_size),
            encoding="utf-8",
        )
        paths.append(path)

    (out_dir / "README.md").write_text(
        _readme(len(batches), batch_size, out_dir),
        encoding="utf-8",
    )
    return paths, len(missing)


def _parse_object(obj: object) -> Iterator[tuple[str, str]]:
    """Yield ``(videoId, label)`` pairs from supported JSON shapes."""
    if isinstance(obj, dict) and isinstance(obj.get("labels"), dict):
        obj = obj["labels"]
    if isinstance(obj, dict):
        for video_id, label in obj.items():
            if isinstance(video_id, str) and isinstance(label, str):
                yield video_id, label
    elif isinstance(obj, list):
        for item in obj:
            if not isinstance(item, dict):
                continue
            video_id = item.get("videoId") or item.get("id")
            label = item.get("label") or item.get("ai_label") or item.get("style")
            if isinstance(video_id, str) and isinstance(label, str):
                yield video_id, label


def _load_json_text(text: str) -> object:
    """Parse JSON, tolerating markdown fences and short explanations."""
    text = text.strip()
    if text.startswith("```"):
        text = text.split("```")[1]
        text = text[4:] if text.lower().startswith("json") else text
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        start, end = text.find("{"), text.rfind("}")
        if start != -1 and end > start:
            return json.loads(text[start : end + 1])
        raise


def import_labels(
    paths: Iterable[Path],
    liked_ids: set[str],
    existing: dict[str, str] | None = None,
    overwrite: bool = False,
) -> tuple[dict[str, str], list[str], dict[str, int]]:
    """Read label files and return valid labels, errors and skip counts."""
    existing = existing or {}
    imported: dict[str, str] = {}
    errors: list[str] = []
    skipped = {"unknown_id": 0, "unknown_label": 0, "already_labelled": 0}

    for path in paths:
        path = Path(path)
        try:
            obj = _load_json_text(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError, IndexError) as exc:
            errors.append(f"{path}: {exc}")
            continue

        for video_id, label in _parse_object(obj):
            if video_id not in liked_ids:
                skipped["unknown_id"] += 1
            elif label not in C.AI_TAGS:
                skipped["unknown_label"] += 1
            elif not overwrite and video_id in existing:
                skipped["already_labelled"] += 1
            else:
                imported[video_id] = label

    return imported, errors, skipped
